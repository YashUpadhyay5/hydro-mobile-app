// Regenerates src/i18n/config.ts from the folders in src/locales, so adding a language or a namespace file is
// "drop the JSON in, run this". Metro needs static imports, which is why this is generated instead of dynamic.
// Run: node scripts/i18n-build-config.cjs
const fs = require('fs');
const path = require('path');

const LOCALES = 'src/locales';
const SKIP_FILES = new Set(['notifications']); // not a registered namespace
const namespaces = fs.readdirSync(path.join(LOCALES, 'en'))
  .map((f) => f.replace(/\.json$/, ''))
  .filter((n) => !SKIP_FILES.has(n))
  .sort();
const langs = ['en', ...fs.readdirSync(LOCALES).filter((d) => d !== 'en' && fs.statSync(path.join(LOCALES, d)).isDirectory()).sort()];
const cap = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const id = (lang, ns) => `${lang}${cap(ns)}`;

const imports = [];
const blocks = [];
for (const lang of langs) {
  const present = namespaces.filter((ns) => fs.existsSync(path.join(LOCALES, lang, ns + '.json')));
  if (!present.length) continue;
  for (const ns of present) imports.push(`import ${id(lang, ns)} from '../locales/${lang}/${ns}.json';`);
  blocks.push(`  ${lang}: {\n${present.map((ns) => `    ${ns}: ${id(lang, ns)},`).join('\n')}\n  },`);
}

const out = `// GENERATED by scripts/i18n-build-config.cjs from src/locales. Edit the JSON files, then re-run the script.
import i18n from 'i18next';
import { initReactI18next } from 'react-i18next';
import { NAMESPACES, DEFAULT_NAMESPACE } from './namespaces';
import { DEFAULT_LANGUAGE_CODE, FALLBACK_LANGUAGES } from './index';

${imports.join('\n')}

export const resources = {
${blocks.join('\n')}
};

let isInitialized = false;

export const initI18n = async (initialLang: string = DEFAULT_LANGUAGE_CODE) => {
  if (isInitialized) return i18n;

  await i18n.use(initReactI18next).init({
    resources,
    lng: initialLang,
    fallbackLng: FALLBACK_LANGUAGES,
    ns: NAMESPACES,
    defaultNS: DEFAULT_NAMESPACE,
    interpolation: {
      escapeValue: false,
    },
    react: {
      useSuspense: false,
    },
  });

  isInitialized = true;
  return i18n;
};

export default initI18n;
`;
fs.writeFileSync('src/i18n/config.ts', out);
console.log(`config.ts: ${langs.join(', ')} x ${namespaces.length} namespaces`);
